//////////////////////////////////////////////////////////////////////////////// the pickable list

static const KeyboardLayoutProfile profiles[KEYBOARD_LAYOUT_COUNT] = {
	{ KEYBOARD_LAYOUT_US,    "US",              &USLayout              },
	{ KEYBOARD_LAYOUT_LATAM, "LATIN AMERICAN",  &LatinAmericanLayout   },
	{ KEYBOARD_LAYOUT_ABNT2, "BRAZILIAN ABNT2", &BrazilianLayout       },
};

const KeyboardLayoutProfile* GetKeyboardLayoutProfile(uint8_t id)
{
	if (id >= KEYBOARD_LAYOUT_COUNT)
		return &profiles[KEYBOARD_LAYOUT_US];
	return &profiles[id];
}

// FabGL starts on the US layout, and so does this, until setup() applies
// whatever was saved in NVS.
static uint8_t currentLayoutId = KEYBOARD_LAYOUT_US;

uint8_t CurrentKeyboardLayoutId()
{
	return currentLayoutId;
}

void SetCurrentKeyboardLayoutId(uint8_t id)
{
	currentLayoutId = GetKeyboardLayoutProfile(id)->id;
}
