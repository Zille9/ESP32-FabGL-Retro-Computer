// No inverse bitmap: inverse video is the bitwise NOT of every glyph
// above (checked for all 128), so RenderFont swaps the colours instead.



AppleFont::AppleFont() 
{
	DEBUG_PRINTLN("Construct Font");
}

AppleFont::~AppleFont() 
{
}

void AppleFont::Create()
{
	int w, h;
	unsigned char* img = read_bmp_memory((char*)normalfont, &w, &h);

	memset(glyphs, 0, sizeof(glyphs));
	for (int n = 0; n < FONT_NUM; n++)
		for (int y = 0; y < FONT_Y; y++)
		{
			unsigned char bits = 0;
			for (int x = 0; x < FONT_X; x++)
				if (img[y * w + (x + n * FONT_X)])
					bits |= 0x40 >> x;
			glyphs[n][y] = bits;
		}

	free(img);
}

// IIe video ROM (342-0265-A): inverse characters are stored already
// inverted, so every glyph renders with inv = false.
void AppleFont::LoadCharRom(const unsigned char* rom)
{
	for (int n = 0; n < 256; n++)
		for (int y = 0; y < FONT_Y; y++)
		{
			unsigned char lit = ~rom[n * 8 + y], bits = 0;
			for (int x = 0; x < FONT_X; x++)
				if (lit & (1 << x))
					bits |= 0x40 >> x;
			glyphs[n][y] = bits;
		}
}

void AppleFont::RenderFont(VGA* vga, int fontnum, int posx, int posy, bool inv,
                           int fg, int bg, int scaleX)
{
	if (vga == NULL)
		return;

	if (inv)
	{
		int t = fg;
		fg = bg;
		bg = t;
	}

	const unsigned char* glyph = glyphs[fontnum & 0xFF];
	const unsigned char fgPair = (fg << 4) | fg;
	const unsigned char bgPair = (bg << 4) | bg;

	for (int y = 0; y < FONT_Y; y++)
	{
		// one scanline lookup per glyph row rather than per pixel
		unsigned char* scanline = vga->row(posy + y);
		unsigned bits = glyph[y];

		if (scaleX == 2 && !(posx & 1))
		{
			// double width at an even x: every font pixel is one whole byte
			unsigned char* p = scanline + (posx >> 1);
			for (int x = 0; x < FONT_X; x++)
				p[x] = (bits & (0x40 >> x)) ? fgPair : bgPair;
		}
		else
		{
			for (int x = 0; x < FONT_X * scaleX; x++)
				VGA::put(scanline, posx + x, (bits & (0x40 >> (x / scaleX))) ? fg : bg);
		}
	}
}

